"""4 GRAPH EXTRACTOR"""

class FxGraphExtractor(BaseFeaturesExtractor):
    """
    GAT Feature Extractor для Stable-Baselines3.

    Принимает батч {'nodes': (B,4,2), 'edges': (B,12,5)},
    строит батчированный граф PyG, прогоняет через два слоя GAT.
    Выдаёт плоский вектор (B, features_dim) для Actor и Critic TD3.

    Архитектура:
      GATConv(2  → 16, heads=4, edge_dim=5) → LeakyReLU → (B*4, 64)
      GATConv(64 → 32, heads=1, edge_dim=5) → LeakyReLU → (B*4, 32)
      Reshape                               →            (B, 128)
      Linear(128 → features_dim) + ReLU + LayerNorm
    """

    def __init__(self, observation_space: spaces.Dict, features_dim: int = 128):
        super().__init__(observation_space, features_dim)

        self.n_nodes = observation_space.spaces['nodes'].shape[0]  # 4
        n_node_feats = observation_space.spaces['nodes'].shape[1]  # 2
        n_edge_feats = observation_space.spaces['edges'].shape[1]  # 5

        # Слой 1: 4 головы внимания, каждая видит признаки рёбер (спред, арбитраж)
        self.gat1 = GATConv(
            in_channels    = n_node_feats,
            out_channels   = 16,
            heads          = 4,
            edge_dim       = n_edge_feats,
            add_self_loops = False,
            dropout        = 0.1,
        )
        # Слой 2: агрегация в 32-мерный эмбеддинг на каждый узел
        self.gat2 = GATConv(
            in_channels    = 16 * 4,  # 4 головы от gat1
            out_channels   = 32,
            heads          = 1,
            edge_dim       = n_edge_feats,
            add_self_loops = False,
        )

        # Топология графа: полносвязный, 4 узла, без петель (12 рёбер)
        # register_buffer → автоматически переносится на GPU вместе с моделью
        src, dst = [], []
        for i in range(self.n_nodes):
            for j in range(self.n_nodes):
                if i != j:
                    src.append(i)
                    dst.append(j)
        self.register_buffer(
            'base_edge_index',
            torch.tensor([src, dst], dtype=torch.long)
        )

        # Финальная проекция: 4 узла × 32 фичи → features_dim
        self.linear = nn.Sequential(
            nn.Linear(self.n_nodes * 32, features_dim),
            nn.ReLU(),
            nn.LayerNorm(features_dim),
        )

    def forward(self, observations: dict) -> torch.Tensor:
        nodes = observations['nodes']  # (B, 4, 2)
        edges = observations['edges']  # (B, 12, 5)
        B     = nodes.shape[0]
        device = nodes.device

        # Вытягиваем батч в плоский формат PyG
        x         = nodes.view(B * self.n_nodes, -1)  # (B*4, 2)
        edge_attr = edges.view(B * 12, -1)             # (B*12, 5)

        # Сдвигаем индексы рёбер для каждого графа в батче
        edge_index = torch.cat(
            [self.base_edge_index + b * self.n_nodes for b in range(B)],
            dim=1
        )

        # GAT прогон
        x = F.leaky_relu(self.gat1(x, edge_index, edge_attr))  # (B*4, 64)
        x = F.leaky_relu(self.gat2(x, edge_index, edge_attr))  # (B*4, 32)

        # Reshape и проекция
        x = x.view(B, self.n_nodes * 32)  # (B, 128)
        return self.linear(x)             # (B, features_dim)


