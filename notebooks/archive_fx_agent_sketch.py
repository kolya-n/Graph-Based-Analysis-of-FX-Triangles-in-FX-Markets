def evaluate(model, df_eval, builder, n_episodes=3):
    """Прогоняет обученного агента на тестовых данных."""
    all_histories = []

    for ep in range(n_episodes):
        env    = FXArbitrageEnv(builder=builder, df_data=df_eval)
        obs, _ = env.reset()
        done   = False

        while not done:
            action, _ = model.predict(obs, deterministic=True)
            obs, _, done, _, info = env.step(action)

        final_nav = env.portfolio_history[-1]
        ret_pct   = (final_nav / env.initial_balance_usd - 1) * 100
        print(f'  Эпизод {ep+1}: NAV ${final_nav:.2f}  ({ret_pct:+.2f}%)')
        all_histories.append(env.portfolio_history)

    return all_histories


