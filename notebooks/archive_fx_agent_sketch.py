# ── Вспомогательные функции ────────────────────────────────────────────────

def get_pair_bid_ask(src: str, dst: str, tick_data: dict) -> Tuple[float, float]:
    """
    Возвращает (bid, ask) для направления src -> dst.
    Если в данных только обратная пара — инвертирует:
      bid(A/B) = 1 / ask(B/A)
      ask(A/B) = 1 / bid(B/A)
    """
    direct  = f'{src}{dst}'
    inverse = f'{dst}{src}'
    if direct in tick_data:
        return tick_data[direct]['bid'], tick_data[direct]['ask']
    elif inverse in tick_data:
        return 1.0 / tick_data[inverse]['ask'], 1.0 / tick_data[inverse]['bid']
    raise KeyError(f'Котировка {src}-{dst} не найдена')


def compute_triangular_arbitrage(
    pairs: List[Tuple[str, str]],
    tick_data: dict,
    currencies: List[str]
) -> dict:
    """
    Перебирает все циклы A->B->C->A.
    Для каждого ребра сохраняет максимальную доходность цикла.
    Значение > 0 = арбитражная возможность существует.
    """
    arb = {pair: 0.0 for pair in pairs}
    for a in currencies:
        for b in currencies:
            if a == b: continue
            for c in currencies:
                if c == a or c == b: continue
                try:
                    r_ab, _ = get_pair_bid_ask(a, b, tick_data)
                    r_bc, _ = get_pair_bid_ask(b, c, tick_data)
                    r_ca, _ = get_pair_bid_ask(c, a, tick_data)
                    cycle   = r_ab * r_bc * r_ca - 1.0
                    for edge in [(a,b),(b,c),(c,a)]:
                        if edge in arb:
                            arb[edge] = max(arb[edge], cycle)
                except KeyError:
                    continue
    return arb


