class FXArbitrageEnv(gym.Env):
    """
    Обновлённая среда с тремя ключевыми улучшениями:

    1. Action space — delta [-1, 1] для каждой non-USD валюты
       Агент говорит "сколько % портфеля переложить", а не "каков целевой вес"
       Если |delta| < TRADE_THRESHOLD → hold, ничего не делаем

    2. Reward = Δ NAV - штраф_за_turnover + hold_bonus
       Агент штрафуется за лишние сделки и поощряется за удержание позиции

    3. prev_weights отслеживаются между шагами
       Агент видит насколько изменился портфель относительно предыдущего шага
    """

    TRADE_THRESHOLD  = 0.05   # меньше 3% изменения → держим позицию
    TURNOVER_PENALTY = 0.1   # штраф за оборот (λ)
    HOLD_BONUS = 0.05         # бонус за бездействие
    MAX_TRADE_FRAC   = 0.3

    def __init__(
        self,
        builder: FxGraphBuilder,
        df_data: pd.DataFrame,
        window_size: int           = WINDOW_SIZE,
        initial_balance_usd: float = 10_000.0,
        max_drawdown: float        = 0.50,
    ):
        super().__init__()
        self.builder             = builder
        self.df_data             = df_data.reset_index(drop=True)
        self.window_size         = window_size
        self.initial_balance_usd = initial_balance_usd
        self.max_drawdown        = max_drawdown
        self.max_steps           = len(df_data) - 1

        # Action: дельты для [EUR, GBP, JPY] от -1 до +1
        # +1 = вложить 100% портфеля в эту валюту
        # -1 = полностью выйти из этой валюты
        # 0  = ничего не делать (hold)
        self.action_space = spaces.Box(
            low=0, high=1.0, shape=(3,), dtype=np.float32
        )
        self.observation_space = spaces.Dict({
            'nodes': spaces.Box(-np.inf, np.inf, shape=(4, N_NODE_FEATS), dtype=np.float32),
            'edges': spaces.Box(-np.inf, np.inf, shape=(12, N_EDGE_FEATS), dtype=np.float32),
        })

        self.balances          = {}
        self.portfolio_history = []
        self.prev_weights      = np.array([1.0, 0.0, 0.0, 0.0])  # [USD, EUR, GBP, JPY]
        self.current_step      = window_size

    # ── Вспомогательные методы ────────────────────────────────────────────

    def _get_nav(self, tick_data: dict) -> float:
        nav = self.balances['USD']
        for ccy in ['EUR', 'GBP', 'JPY']:
            amount = self.balances.get(ccy, 0.0)
            if amount > 1e-9:
                try:
                    bid, _ = get_pair_bid_ask(ccy, 'USD', tick_data)
                    nav   += amount * bid
                except KeyError:
                    pass
        return nav

    def _get_weights(self, tick_data: dict, nav: float) -> np.ndarray:
        """Текущие веса портфеля [USD, EUR, GBP, JPY]."""
        weights = []
        for ccy in self.builder.currencies:
            amount = self.balances.get(ccy, 0.0)
            if ccy == 'USD':
                weights.append(amount / nav)
            else:
                try:
                    bid, _ = get_pair_bid_ask(ccy, 'USD', tick_data)
                    weights.append(amount * bid / nav)
                except KeyError:
                    weights.append(0.0)
        return np.array(weights)

    def _execute_trade(self, ccy: str, delta_usd: float, tick_data: dict):
        """
        Все сделки проводим через прямые котировки CCY/USD:
          Покупка CCY: тратим delta_usd USD, получаем delta_usd / ask_CCY_USD
          Продажа CCY: получаем delta_usd USD, отдаём delta_usd / bid_CCY_USD
        """
        try:
            bid_ccy_usd, ask_ccy_usd = get_pair_bid_ask(ccy, 'USD', tick_data)
        except KeyError:
            return

        if delta_usd > 1e-6:
            # Покупаем CCY: платим Ask (худший курс для нас)
            if self.balances['USD'] >= delta_usd:
                self.balances['USD'] -= delta_usd
                self.balances[ccy]   += delta_usd / ask_ccy_usd  # ← всегда делим

        elif delta_usd < -1e-6:
            # Продаём CCY: получаем Bid (худший курс для нас)
            amount_to_sell_usd = abs(delta_usd)
            amount_ccy         = amount_to_sell_usd / bid_ccy_usd  # ← всегда делим
            if self.balances.get(ccy, 0.0) >= amount_ccy:
                self.balances[ccy]   -= amount_ccy
                self.balances['USD'] += amount_to_sell_usd

    # ── Основные методы Gym ───────────────────────────────────────────────

    def reset(self, seed=None, options=None):
        super().reset(seed=seed)
        self.current_step      = self.window_size
        self.balances          = {
            'USD': self.initial_balance_usd,
            'EUR': 0.0,
            'GBP': 0.0,
            'JPY': 0.0
        }
        self.portfolio_history = [self.initial_balance_usd]
        self.prev_weights      = np.array([1.0, 0.0, 0.0, 0.0])
        return self._get_obs(), {}

    def _get_obs(self) -> dict:
        window = self.df_data.iloc[self.current_step - self.window_size : self.current_step]
        graph  = self.builder.build(df_window=window, agent_balances=self.balances)
        return {
            'nodes': graph.x.numpy().astype(np.float32),
            'edges': graph.edge_attr.numpy().astype(np.float32),
        }

    def step(self, action: np.ndarray):
        tick_data  = self.builder._parse_tick(self.df_data.iloc[self.current_step])
        nav_before = self._get_nav(tick_data)

        non_usd  = ['EUR', 'GBP', 'JPY']
        turnover = 0.0
        traded   = False

        # ── ИЗМЕНЕНО: считаем текущие веса и торгуем до целевых ──────────
        current_weights = self._get_weights(tick_data, nav_before)
        # current_weights = [w_USD, w_EUR, w_GBP, w_JPY]

        for i, ccy in enumerate(non_usd):
            # action[i] = желаемый вес для этой валюты (0 до 1)
            # Интерпретируем action как ЦЕЛЕВОЙ вес, а не дельту
            target_weight  = np.clip(float(action[i]), 0.0, self.MAX_TRADE_FRAC)
            current_weight = current_weights[i + 1]  # +1 потому что [0]=USD
            delta_weight   = target_weight - current_weight

            if abs(delta_weight) < self.TRADE_THRESHOLD:
                continue

            delta_usd = delta_weight * nav_before
            self._execute_trade(ccy, delta_usd, tick_data)
            turnover += abs(delta_weight)
            traded    = True
        # ─────────────────────────────────────────────────────────────────

        nav_after = self._get_nav(tick_data)
        current_weights = self._get_weights(tick_data, nav_after)

        # Компонент 1: изменение NAV
        delta_nav = nav_after - nav_before

        # Компонент 2: штраф за оборот (чем больше торгуем — тем больше штраф)
        turnover_penalty = self.TURNOVER_PENALTY * turnover * nav_before / 10_000

        # Компонент 3: бонус за hold (агент не торговал → маленький плюс)
        hold_bonus = self.HOLD_BONUS if not traded else 0.0

        reward = delta_nav - turnover_penalty + hold_bonus

        self.prev_weights = current_weights
        self.portfolio_history.append(nav_after)

        # ── Условие завершения ────────────────────────────────────────────
        self.current_step += 1
        done = self.current_step >= self.max_steps

        peak = max(self.portfolio_history)
        if (peak - nav_after) / peak > self.max_drawdown:
            done    = True
            reward -= 50.0

        info = {
            'nav':      nav_after,
            'turnover': turnover,
            'traded':   traded,
            'weights':  current_weights,
        }
        return self._get_obs(), float(reward), done, False, info


