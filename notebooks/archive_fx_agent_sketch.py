class PortfolioLoggerCallback(BaseCallback):
    def __init__(self, log_every=500, verbose=0):
        super().__init__(verbose)
        self.log_every       = log_every
        self.episode_rewards = []
        self.episode_navs    = []
        self._ep_reward      = 0.0
        self._window_navs    = []
        self._window_rewards = []

    def _on_step(self) -> bool:
        info    = self.locals['infos'][0]
        reward  = self.locals['rewards'][0]
        nav     = info.get('nav', 0)

        self._ep_reward += reward
        self._window_navs.append(nav)
        self._window_rewards.append(reward)

        if self.num_timesteps % self.log_every == 0:
            w_nav = self._window_navs[-self.log_every:]
            w_rew = self._window_rewards[-self.log_every:]

            avg_nav  = np.mean(w_nav)
            min_nav  = np.min(w_nav)
            max_nav  = np.max(w_nav)
            avg_rew  = np.mean(w_rew)
            ep_count = len(self.episode_rewards)
            ep_avg_r = np.mean(self.episode_rewards[-10:]) if ep_count > 0 else 0.0

            print(
                f'[{self.num_timesteps:>6}/100000] '
                f'NAV: ${avg_nav:>9,.2f} '
                f'[${min_nav:>8,.2f} – ${max_nav:>8,.2f}]  '
                f'R_step: {avg_rew:>+7.5f}  '
                f'R_ep(last10): {ep_avg_r:>+8.4f}  '
                f'turnover: {info.get("turnover", 0):.4f}  '
                f'traded: {"✅" if info.get("traded", False) else "❌"}  '
                f'episodes: {ep_count}'
            )

        if self.locals['dones'][0]:
            self.episode_rewards.append(self._ep_reward)
            self.episode_navs.append(nav)
            self._ep_reward = 0.0

        return True


